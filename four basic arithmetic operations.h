#include<iostream>
using namespace std;
long long add(long long a,long long b){
    return a+b;
}
long long subtract(long long a,long long b){
    return a-b;
}
long long multiply(long long a,long long b){
    return a * b;
}
long long divide(long long a,long long b){
    return a / b;
}
long long mod(long long a,long long b){
    return a % b;
}